/* T206 歌词跨行拖动的行归属判据 rowOfY（v3.34.5，审计 P3-2）
   ---------------------------------------------------------------------------
   覆盖率报告长期列出 4 个「从未执行的函数」，rowOfY 是其中唯一带真实业务语义的一个：
   它是歌词字块**跨行拖动**时「指针落在第几行」的判据（v3.33.18 重写为按每行真实矩形命中）。
   真机拖拽手势在桩里跑不起来（需要真实行矩形 + 多指/指针序列），于是这条路径
   **长期只靠人工验收**——97.9% 的覆盖率数字并不包含它，是个安静的盲区。

   处置：它是纯函数（只吃 geo.rects 与 y），按仓库既有先例（lyricNeighbors / swapChars 等
   「供测试与排查」的导出）把它导出，直接单测判据本身。
   ★ 这不替代真机验收——手势能否触发、拖拽手感仍需人跑（见 C-8）；
     但"落在哪一行"这个**算法**从此不再是没有机器把关的裸奔代码。

   钉四条：行内命中 / 行间缝隙取最近 / 越界钳到首末行 / rects 为空兜第 0 行。 */
const { loadApp, eq, section } = require("../lib/harness");

/* 三行等高的假矩形（i 是行号；top/bottom 是行的真实上下沿，中间留 8px 缝隙） */
const GEO = {
  rects: [
    { i: 0, top: 100, bottom: 180 },
    { i: 1, top: 188, bottom: 268 },
    { i: 2, top: 276, bottom: 356 },
  ],
};

section("T206 rowOfY · 歌词跨行拖动的行归属判据");
{
  const app = loadApp();
  const rowOfY = app.beat.Arrange.rowOfY;
  eq(typeof rowOfY, "function", "★ rowOfY 已导出（此前覆盖率显示它从未被执行）");

  /* ① 行内命中：上下沿都算本行（半开区间两端的包含性由 d=0 保证） */
  eq(rowOfY(GEO, 100), 0, "行 0 上沿 → 行 0");
  eq(rowOfY(GEO, 140), 0, "★ 行 0 中间 → 行 0");
  eq(rowOfY(GEO, 180), 0, "行 0 下沿 → 行 0");
  eq(rowOfY(GEO, 220), 1, "★ 行 1 中间 → 行 1");
  eq(rowOfY(GEO, 320), 2, "★ 行 2 中间 → 行 2");

  /* ② 行间缝隙取最近的一行（v3.33.18 的核心：不允许"掉进缝里就没归属"） */
  eq(rowOfY(GEO, 184), 0, "★ 缝隙 180~188 的上半（184）→ 最近的上一行 0");
  eq(rowOfY(GEO, 186), 1, "★ 缝隙下半（186）→ 最近的下一行 1");
  eq(rowOfY(GEO, 272), 1, "缝隙 268~276 上半 → 行 1");
  eq(rowOfY(GEO, 274), 2, "缝隙下半 → 行 2");

  /* ③ 越界钳到首末行（指针跑出轨道上下方，不能返回 undefined/负数） */
  eq(rowOfY(GEO, -500), 0, "★ 远在第一行之上 → 钳到行 0");
  eq(rowOfY(GEO, 0), 0, "y=0 → 行 0");
  eq(rowOfY(GEO, 9999), 2, "★ 远在最后一行之下 → 钳到末行 2");

  /* ④ 兜底：rects 缺失/为空（几何还没采到时的首帧）不得抛异常，回第 0 行 */
  eq(rowOfY({}, 140), 0, "★ 无 rects 字段 → 兜第 0 行（不炸）");
  eq(rowOfY({ rects: [] }, 140), 0, "★ rects 为空数组 → 兜第 0 行（不炸）");

  /* ⑤ 单行：任何 y 都只能落在第 0 行（lctx.rows === 1 时 rowOfY 本不该激活，但也不能越界） */
  eq(rowOfY({ rects: [{ i: 0, top: 50, bottom: 130 }] }, 9999), 0, "单行几何 → 恒为行 0");
}
